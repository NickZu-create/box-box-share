const assert=require('node:assert/strict');
const c=require('./design-preview/demo-core.js');
const me=text=>({sender:'me',text}),peer=text=>({sender:'peer',text});
assert.equal(c.canSeeContacts([]),false);
assert.equal(c.canSeeContacts([me('a'),me('b'),me('c'),me('d')]),false);
assert.equal(c.canSeeContacts([me('a'),peer('b'),me('c')]),false);
assert.equal(c.canSeeContacts([me('a'),peer('b'),me('c'),peer('d')]),true);
assert.equal(c.canSeeContacts([me('a'),peer('b'),me('c'),{sender:'system',text:'notice'}]),false);
assert.equal(c.canSeeContacts([me('a'),peer('b'),me('c'),peer(' ')]),false);
assert.deepEqual(c.defaults(new Date('2026-12-31T20:30:00Z')),{start:'2027-01-01T04:30',end:'2027-01-08T04:30',deposit:0,location:'CityUHK campus',maxDays:7});
assert.equal(c.deriveTitle('  二手课本。保存完好  '),'二手课本');
assert.equal(c.deriveTitle('Calculator in good condition. Includes cover'),'Calculator in good condition');
assert.deepEqual(c.rentalQuote('2026-11-02T12:00','2026-11-03T12:01',12,100),{days:2,rent:24,deposit:100});
assert.equal(c.rentalQuote('2026-11-03T12:00','2026-11-02T12:00',12),null);
assert.equal(c.readPayload('#listing=%7Bbad'),null);
const hash='#'+new URLSearchParams({listing:JSON.stringify({id:'example',intent:'sale',description:'Calculator.',amount:80})});
assert.equal(c.readPayload(hash).title,'Calculator');
assert.equal(c.readPayload('#'+new URLSearchParams({listing:JSON.stringify({intent:'sale',description:'x',amount:-1})})),null);
console.log('14 focused demo-rule checks passed');
